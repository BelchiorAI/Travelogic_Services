import { defineConfig } from "@lovable.dev/vite-tanstack-config";

// BUILD_TARGET=static builds a single-page app of plain files (no server), for static hosting
// such as Render static sites. Any other build (including Lovable's) is unchanged.
const staticSpa = process.env["BUILD_TARGET"] === "static";

export default defineConfig({
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
    ...(staticSpa ? { spa: { enabled: true } } : {}),
  },
  ...(staticSpa ? { nitro: false as const } : {}),
});
